// 國中數學題庫：每行一題「題目|正確答案|錯誤1|錯誤2|錯誤3」
// groups 給「分類」遊戲用：{ 類別名稱: [項目, ...] }
const UNITS = [];
function U(id, grade, chapter, title, text, groups) {
  const items = text.trim().split('\n').map(line => {
    const [q, a, ...w] = line.trim().split('|');
    return { q, a, w };
  });
  UNITS.push({ id, grade, chapter, title, items, groups: groups || null });
}

